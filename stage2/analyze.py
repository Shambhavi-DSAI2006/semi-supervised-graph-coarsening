"""Summarise Stage 2 results and apply the pre-registered decision rule (PROTOCOL.md).

    python analyze.py            # reads results/results*.jsonl

Writes results/summary.md and figures/label_budget.png.
"""
import glob, json, os
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
BUDGETS = ["5pc", "20pc", "10pct", "pool"]
BUDGET_NAME = {"5pc": "5 / class", "20pc": "20 / class", "10pct": "10%", "pool": "whole pool"}
LOW = ["5pc", "20pc"]
RATIOS = [0.3, 0.1]
METHODS = ["sgbgc", "sgbgc_keep", "loukas", "gb_struct", "feat_cluster"]
LABEL_FREE = ["loukas", "gb_struct", "feat_cluster"]
NAME = {"full": "Full graph (M1)", "sgbgc": "SGBGC (M2)", "sgbgc_keep": "SGBGC-keep (M3)",
        "loukas": "Loukas/SCAL (M4)", "gb_struct": "GB-struct (M5)", "feat_cluster": "Feature clustering (M6)"}
DATASETS = ["cora", "citeseer"]
DS_NAME = {"cora": "Cora", "citeseer": "Citeseer"}

rows = []
for p in sorted(glob.glob(os.path.join(HERE, "results", "results*.jsonl"))):
    rows += [json.loads(l) for l in open(p)]

# latest record per (dataset, seed, budget, method, ratio) wins
recs = {}
for r in rows:
    recs[(r["dataset"], r["seed"], r["budget"], r["method"], r["ratio_target"])] = r
R = list(recs.values())


def acc(ds, budget, method, ratio=None):
    """Per-seed test accuracies (%) keyed by seed."""
    return {r["seed"]: 100 * r["test"] for r in R if r["dataset"] == ds and r["budget"] == budget
            and r["method"] == method and (method == "full" or r["ratio_target"] == ratio)}


def field(ds, budget, method, ratio, key):
    v = [r[key] for r in R if r["dataset"] == ds and r["budget"] == budget
         and r["method"] == method and r["ratio_target"] == ratio]
    return float(np.mean(v)) if v else float("nan")


def ms(d):
    v = np.array(list(d.values()))
    return f"{v.mean():.1f} ± {v.std():.1f}" if len(v) else "—"


def low_cells_mean(ds, method):
    """Mean test accuracy over low budgets x both ratios (the decision rule's 4 cells)."""
    vals = [np.mean(list(acc(ds, b, method, r).values())) for b in LOW for r in RATIOS]
    return float(np.mean(vals))


def paired_gap(ds, a, b):
    """Per-seed gap a - b averaged over the 4 low cells; returns mean and 95% CI half-width over seeds."""
    seeds = sorted(set.intersection(*[set(acc(ds, bud, m, r)) for bud in LOW for r in RATIOS for m in (a, b)]))
    per_seed = [np.mean([acc(ds, bud, a, r)[s] - acc(ds, bud, b, r)[s] for bud in LOW for r in RATIOS]) for s in seeds]
    per_seed = np.array(per_seed)
    half = 1.96 * per_seed.std(ddof=1) / np.sqrt(len(per_seed)) if len(per_seed) > 1 else float("nan")
    return per_seed.mean(), half, len(per_seed)


out = ["# Stage 2 results — label-scarcity test", "",
       f"{len(R)} training runs. Test accuracy (%), mean ± std over seeds. Generated by `analyze.py`.", ""]

# ---------------------------------------------------------------- decision rule
out += ["## Decision (pre-registered rule)", ""]
out += ["| Dataset | Best label-free method | H1 gap: SGBGC-keep − SGBGC | H2 gap: SGBGC-keep − best label-free |",
        "|---|---|---|---|"]
verdict = {}
for ds in DATASETS:
    if not acc(ds, "5pc", "full"):
        continue
    lf_means = {m: low_cells_mean(ds, m) for m in LABEL_FREE}
    best = max(lf_means, key=lf_means.get)
    keep = low_cells_mean(ds, "sgbgc_keep")
    h1 = keep - low_cells_mean(ds, "sgbgc")
    h2 = keep - lf_means[best]
    g1, c1, n1 = paired_gap(ds, "sgbgc_keep", "sgbgc")
    g2, c2, n2 = paired_gap(ds, "sgbgc_keep", best)
    verdict[ds] = (h1, h2)
    out.append(f"| {DS_NAME[ds]} | {NAME[best]} ({lf_means[best]:.1f}) | {h1:+.2f} (95% CI ±{c1:.2f}) | {h2:+.2f} (95% CI ±{c2:.2f}) |")

EXPECTED_SEEDS = 10
min_seeds = min([len(acc(ds, b, m, r)) for ds in DATASETS for b in BUDGETS for m in METHODS for r in RATIOS]
                + [len(acc(ds, b, "full")) for ds in DATASETS for b in BUDGETS])
if min_seeds < EXPECTED_SEEDS:
    out += ["", f"- **PROVISIONAL — incomplete run** (some cells have only {min_seeds} of {EXPECTED_SEEDS} seeds). "
            "The decision rule is applied only to the complete run."]
elif len(verdict) == len(DATASETS):
    h2s = [verdict[d][1] for d in DATASETS]
    h1s = [verdict[d][0] for d in DATASETS]
    if all(g >= 2 for g in h2s):
        dec = "**GO** — SGBGC-keep beats the best label-free method by ≥ 2 points on both datasets."
    elif all(g <= 1 for g in h2s):
        dec = "**PIVOT** — SGBGC-keep is ≤ 1 point better than the best label-free method on both datasets."
    else:
        dec = "**INCONCLUSIVE** — extend to Co-CS before deciding."
    h1v = ("supported" if all(g >= 2 for g in h1s) else "refuted" if all(g <= 1 for g in h1s) else "unclear")
    out += ["", f"- Decision: {dec}", f"- H1 (discarding unlabelled nodes is the main cause): **{h1v}**."]
out += ["", "Gaps are means over the low-label budgets (5 and 20 per class) and both ratios. "
        "CIs are over seeds, from paired per-seed differences (reported, not part of the rule).", ""]

# ---------------------------------------------------------------- full tables
for ds in DATASETS:
    if not acc(ds, "5pc", "full"):
        continue
    out += [f"## {DS_NAME[ds]}", ""]
    for ratio in RATIOS:
        out += [f"### Ratio {ratio}", "",
                "| Method | " + " | ".join(BUDGET_NAME[b] for b in BUDGETS) + " |",
                "|---|" + "---|" * len(BUDGETS)]
        out.append(f"| {NAME['full']} | " + " | ".join(ms(acc(ds, b, 'full')) for b in BUDGETS) + " |")
        for m in METHODS:
            out.append(f"| {NAME[m]} | " + " | ".join(ms(acc(ds, b, m, ratio)) for b in BUDGETS) + " |")
        out.append("")
        out += ["Super-nodes / original nodes kept in the coarse graph (mean over seeds):", "",
                "| Method | " + " | ".join(BUDGET_NAME[b] for b in BUDGETS) + " |",
                "|---|" + "---|" * len(BUDGETS)]
        for m in METHODS:
            out.append(f"| {NAME[m]} | " + " | ".join(
                f"{field(ds, b, m, ratio, 'super_nodes'):.0f} / {field(ds, b, m, ratio, 'nodes_kept'):.0f}" for b in BUDGETS) + " |")
        out.append("")

os.makedirs(os.path.join(HERE, "results"), exist_ok=True)
open(os.path.join(HERE, "results", "summary.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))

# ---------------------------------------------------------------- figure
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

style = {"full": ("#222222", "--", "o"), "sgbgc": ("#d62728", "-", "x"), "sgbgc_keep": ("#1f77b4", "-", "o"),
         "loukas": ("#7f7f7f", "-", "s"), "gb_struct": ("#bcbd22", "-", "^"), "feat_cluster": ("#9467bd", "-", "D")}
dss = [d for d in DATASETS if acc(d, "5pc", "full")]
fig, axes = plt.subplots(len(dss), 2, figsize=(11, 4.2 * len(dss)), squeeze=False)
xs = np.arange(len(BUDGETS))
for i, ds in enumerate(dss):
    for j, ratio in enumerate(RATIOS):
        ax = axes[i][j]
        for m in ["full"] + METHODS:
            means, sds = [], []
            for b in BUDGETS:
                v = np.array(list(acc(ds, b, m, ratio).values()))
                means.append(v.mean() if len(v) else np.nan); sds.append(v.std() if len(v) else np.nan)
            c, ls, mk = style[m]
            ax.errorbar(xs, means, yerr=sds, color=c, ls=ls, marker=mk, capsize=2, lw=1.4, ms=4, label=NAME[m])
        ax.axvspan(-0.3, 1.3, color="#1f77b4", alpha=0.06)
        ax.set_xticks(xs, [BUDGET_NAME[b] for b in BUDGETS])
        ax.set_title(f"{DS_NAME[ds]}, keep {int(ratio * 100)}% of nodes", fontsize=10)
        ax.set_ylabel("Test accuracy (%)"); ax.grid(axis="y", alpha=0.3)
        ax.spines[["top", "right"]].set_visible(False)
axes[0][0].legend(fontsize=7, frameon=False, loc="lower right")
fig.suptitle("Accuracy vs. training-label budget (shaded: low-label budgets used by the decision rule)", fontsize=11)
fig.tight_layout()
os.makedirs(os.path.join(HERE, "figures"), exist_ok=True)
fig.savefig(os.path.join(HERE, "figures", "label_budget.png"), dpi=150)
print("wrote results/summary.md and figures/label_budget.png")
